function renewssws(){
clear
_box_top
_bcenter "• RENEW SSWS USER •"
_box_bot
_box_top
NUMBER_OF_CLIENTS=$(grep -c -E "^## " "/etc/xray/config.json")
if [[ ${NUMBER_OF_CLIENTS} == '0' ]]; then
_bline "• You have no existing clients!"
_box_bot
_byline
echo ""
read -n 1 -s -r -p "   Press any key to back on menu"
menu-ss
fi
clear
_box_top
_bcenter "• RENEW SSWS USER •"
_box_bot
_box_top
grep -E "^## " "/etc/xray/config.json" | cut -d ' ' -f 2-3 | column -t | sort | uniq | nl
_bline ""
_bline "• [NOTE] Press any key to back on menu"
_box_bot
_byline
echo -e "$COLOR1───────────────────────────────────────────────────${NC}"
read -rp "   Input Username : " user
if [ -z $user ]; then
menu-ss
else
read -p "   Expired (days): " masaaktif
if [ -z $masaaktif ]; then
masaaktif="1"
fi
exp=$(grep -E "^## $user" "/etc/xray/config.json" | cut -d ' ' -f 3 | sort | uniq)
now=$(date +%Y-%m-%d)
d1=$(date -d "$exp" +%s)
d2=$(date -d "$now" +%s)
exp2=$(( (d1 - d2) / 86400 ))
exp3=$(($exp2 + $masaaktif))
exp4=`date -d "$exp3 days" +"%Y-%m-%d"`
sed -i "/## $user/c\## $user $exp4" /etc/xray/config.json
systemctl restart xray > /dev/null 2>&1
clear
_box_top
_bcenter "• RENEW SSWS USER •"
_box_bot
_box_top
_bline "[INFO]  $user Account Renewed Successfully"
_bline ""
_bline "Client Name : $user"
_bline "Days Added  : $masaaktif Days"
_bline "Expired On  : $exp4"
_box_bot
_byline
echo ""
read -n 1 -s -r -p "   Press any key to back on menu"
menu-ss
fi
}

